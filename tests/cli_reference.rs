//! The docs site's command reference (`docs-site/docs/reference/commands/`) is generated
//! from the clap definitions: every page is the `--help` of the real `airs` binary, walked
//! from the root down through each help's `Commands:` block. This test renders the pages
//! again and fails when the committed ones differ, are missing or are extra.
//!
//! `AIRS_UPDATE_CLI_REFERENCE=1` rewrites the committed pages instead (and passes);
//! `scripts/cli-reference.sh` runs that. The walk runs with no tenant and a cleared
//! environment, so it sends no request.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Where the pages live, relative to the repository root.
const DIR: &str = "docs-site/docs/reference/commands";
/// The command that regenerates the pages.
const REGENERATE: &str = "scripts/cli-reference.sh";
const MARKER: &str = "<!-- Generated by scripts/cli-reference.sh from the clap definitions \
                      (tests/cli_reference.rs). Do not edit by hand. -->";

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// One command: its path below the root (empty for the root) and its help text.
struct Help {
    path: Vec<String>,
    text: String,
}

/// Runs `airs <args>` in a private empty directory with a cleared environment whose
/// store, HOME and XDG directories lie inside it.
fn help_of(sandbox: &Path, args: &[&str]) -> String {
    let out = Command::new(env!("CARGO_BIN_EXE_airs"))
        .args(args)
        .current_dir(sandbox)
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("HOME", sandbox.join("home"))
        .env("XDG_CONFIG_HOME", sandbox.join("config"))
        .env("XDG_STATE_HOME", sandbox.join("state"))
        .env("XDG_DATA_HOME", sandbox.join("data"))
        .env("AIRS_CLI_CONFIG_DIR", sandbox.join("store"))
        .env("NO_COLOR", "1")
        .output()
        .unwrap();
    let stdout = String::from_utf8(out.stdout).unwrap();
    let stderr = String::from_utf8(out.stderr).unwrap();
    assert!(
        out.status.code() == Some(0) && stderr.is_empty(),
        "airs {args:?}: exit {:?}, stderr {stderr:?}",
        out.status.code()
    );
    stdout
}

/// The subcommand names of a help text's `Commands:` block, in clap's order, `help` left
/// out.
fn subcommands(help: &str) -> Vec<String> {
    help.split_once("\nCommands:\n")
        .map(|(_, rest)| {
            rest.lines()
                .take_while(|line| line.starts_with("  "))
                .filter_map(|line| line.split_whitespace().next())
                .filter(|name| *name != "help")
                .map(str::to_owned)
                .collect()
        })
        .unwrap_or_default()
}

/// Every command's help, depth first in clap's order.
fn walk(sandbox: &Path, path: Vec<String>, found: &mut Vec<Help>) {
    let mut args: Vec<&str> = path.iter().map(String::as_str).collect();
    args.push("--help");
    let text = help_of(sandbox, &args);
    let children = subcommands(&text);
    found.push(Help {
        path: path.clone(),
        text,
    });
    for name in children {
        let mut next = path.clone();
        next.push(name);
        walk(sandbox, next, found);
    }
}

fn command_line(path: &[String]) -> String {
    if path.is_empty() {
        "airs".to_owned()
    } else {
        format!("airs {}", path.join(" "))
    }
}

/// A fenced `text` block whose fence is longer than any backtick run in `text`.
fn fenced(text: &str) -> String {
    let longest = text.split(|c| c != '`').map(str::len).max().unwrap_or(0);
    let fence = "`".repeat(longest.max(2) + 1);
    format!("{fence}text\n{}\n{fence}\n", text.trim_end())
}

/// The first line of a help text: the command's summary.
fn summary(text: &str) -> &str {
    text.lines().next().unwrap_or("").trim()
}

/// The pages: `index.md` (the root help and one link per top-level command) and one page
/// per top-level command holding it and every command below it.
fn render(helps: &[Help]) -> BTreeMap<String, String> {
    let mut pages = BTreeMap::new();
    let root = helps
        .iter()
        .find(|help| help.path.is_empty())
        .expect("the root help");
    let tops: Vec<&Help> = helps.iter().filter(|help| help.path.len() == 1).collect();

    let mut index = format!(
        "---\ntitle: Command reference\nsidebar_label: Overview\nsidebar_position: 0\n---\n\n{MARKER}\n\n\
         # Command reference\n\n\
         Every page in this section is the `--help` text of `airs`, generated from its clap \
         definitions. `airs-cli` and `airs-cli-rs` run the same program and print the same \
         help.\n\n| Command | Summary |\n|---|---|\n"
    );
    for top in &tops {
        let name = &top.path[0];
        index.push_str(&format!(
            "| [`{}`](./{name}.md) | {} |\n",
            command_line(&top.path),
            summary(&top.text).replace('|', "\\|")
        ));
    }
    index.push_str(&format!("\n## airs\n\n{}", fenced(&root.text)));
    pages.insert("index.md".to_owned(), index);

    for (position, top) in tops.iter().enumerate() {
        let name = &top.path[0];
        let mut page = format!(
            "---\ntitle: airs {name}\nsidebar_label: {name}\nsidebar_position: {}\n---\n\n{MARKER}\n\n",
            position + 1
        );
        for help in helps.iter().filter(|help| help.path.first() == Some(name)) {
            let level = help.path.len().min(6);
            page.push_str(&format!(
                "{} {}\n\n{}\n",
                "#".repeat(level),
                command_line(&help.path),
                fenced(&help.text)
            ));
        }
        let page = format!("{}\n", page.trim_end());
        pages.insert(format!("{name}.md"), page);
    }
    pages
}

fn committed(dir: &Path) -> BTreeMap<String, String> {
    let Ok(entries) = fs::read_dir(dir) else {
        return BTreeMap::new();
    };
    entries
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.is_file())
        .map(|path| {
            let name = path.file_name().unwrap().to_string_lossy().into_owned();
            let text = fs::read_to_string(&path).unwrap_or_default();
            (name, text)
        })
        .collect()
}

#[test]
fn the_command_reference_is_current() {
    let sandbox = PathBuf::from(env!("CARGO_TARGET_TMPDIR"))
        .join(format!("cli-reference-{}", std::process::id()));
    let _ = fs::remove_dir_all(&sandbox);
    fs::create_dir_all(&sandbox).unwrap();
    let mut helps = Vec::new();
    walk(&sandbox, Vec::new(), &mut helps);
    let _ = fs::remove_dir_all(&sandbox);
    assert!(
        helps.len() > 150,
        "every command was walked: {}",
        helps.len()
    );
    let expected = render(&helps);
    let dir = root().join(DIR);

    if std::env::var_os("AIRS_UPDATE_CLI_REFERENCE").is_some_and(|value| value == "1") {
        fs::create_dir_all(&dir).unwrap();
        for name in committed(&dir).keys() {
            if !expected.contains_key(name) {
                fs::remove_file(dir.join(name)).unwrap();
            }
        }
        for (name, text) in &expected {
            fs::write(dir.join(name), text).unwrap();
        }
        eprintln!("cli-reference: wrote {} pages to {DIR}", expected.len());
        return;
    }

    let actual = committed(&dir);
    let mut problems = Vec::new();
    for (name, text) in &expected {
        match actual.get(name) {
            None => problems.push(format!("missing: {DIR}/{name}")),
            Some(found) if found != text => problems.push(format!("stale: {DIR}/{name}")),
            Some(_) => {}
        }
    }
    for name in actual.keys() {
        if !expected.contains_key(name) {
            problems.push(format!("extra: {DIR}/{name}"));
        }
    }
    assert!(
        problems.is_empty(),
        "the command reference does not match the clap definitions; run {REGENERATE}:\n{}",
        problems.join("\n")
    );
}

#[test]
fn rendering_helpers_behave() {
    assert_eq!(fenced("a\n"), "```text\na\n```\n");
    assert_eq!(fenced("x ```` y"), "`````text\nx ```` y\n`````\n");
    assert_eq!(
        subcommands("Usage: airs\n\nCommands:\n  tenant  Tenants\n  help    Help\n\nOptions:\n"),
        ["tenant"]
    );
    assert_eq!(command_line(&[]), "airs");
    assert_eq!(
        command_line(&["runtime".to_owned(), "scan".to_owned()]),
        "airs runtime scan"
    );
}
